; Copy _crc_table to SRAM 0xAA00. Lives in bank 11 with the table.
; Call it only while bank 11 is mapped. Cartridge RAM is already
; enabled. Interrupts are already off.
_crc_load::
        di
        push    bc
        push    de
        push    hl
        ld      hl, #_crc_table
        ld      de, #0xAA00
        ld      b, #4
001$:
        ld      c, #0
002$:
        ld      a, (hl+)
        ld      (de), a
        inc     de
        dec     c
        jr      nz, 002$
        dec     b
        jr      nz, 001$
        pop     hl
        pop     de
        pop     bc
        ret

; Write 0xFF over the scratch table so unused save RAM stays blank.
_crc_clear::
        push    bc
        push    hl
        ld      hl, #0xAA00
        ld      a, #0xFF
        ld      b, #4
003$:
        ld      c, #0
004$:
        ld      (hl+), a
        dec     c
        jr      nz, 004$
        dec     b
        jr      nz, 003$
        pop     hl
        pop     bc
        ret

