; One 16 KB window. crc_ptr is the window base. crc_state is the
; running CRC, little-endian, without the final complement.
; C = byte 0, B = byte 1, E = byte 2, D = byte 3.
; SP walks the window. 0xFFF0 holds the second popped byte.
; 0xFFF1 / 0xFFF2 count 16 * 256 passes of 2 word-pairs
; (16 * 256 * 4 = 16384 bytes, one bank).
_crc_win::
        di
        push    bc
        push    de
        push    hl
        ld      (#_crc_sp), sp
        ld      a, (#_crc_state)
        ld      c, a
        ld      a, (#_crc_state + 1)
        ld      b, a
        ld      a, (#_crc_state + 2)
        ld      e, a
        ld      a, (#_crc_state + 3)
        ld      d, a
        ld      a, (#_crc_ptr)
        ld      l, a
        ld      a, (#_crc_ptr + 1)
        ld      h, a
        ld      sp, hl
        ld      a, #16
        ldh     (0xF2), a
006$:
        xor     a
        ldh     (0xF1), a
005$:

        pop     hl
        ld      a, h
        ldh     (0xF0), a
        ld      a, l
        xor     c
        ld      l, a
        ld      h, #0xAA
        ld      a, (hl)
        xor     b
        ld      c, a
        inc     h
        ld      a, (hl)
        xor     e
        ld      b, a
        inc     h
        ld      a, (hl)
        xor     d
        ld      e, a
        inc     h
        ld      a, (hl)
        ld      d, a
        ldh     a, (0xF0)
        xor     c
        ld      l, a
        ld      h, #0xAA
        ld      a, (hl)
        xor     b
        ld      c, a
        inc     h
        ld      a, (hl)
        xor     e
        ld      b, a
        inc     h
        ld      a, (hl)
        xor     d
        ld      e, a
        inc     h
        ld      a, (hl)
        ld      d, a

        pop     hl
        ld      a, h
        ldh     (0xF0), a
        ld      a, l
        xor     c
        ld      l, a
        ld      h, #0xAA
        ld      a, (hl)
        xor     b
        ld      c, a
        inc     h
        ld      a, (hl)
        xor     e
        ld      b, a
        inc     h
        ld      a, (hl)
        xor     d
        ld      e, a
        inc     h
        ld      a, (hl)
        ld      d, a
        ldh     a, (0xF0)
        xor     c
        ld      l, a
        ld      h, #0xAA
        ld      a, (hl)
        xor     b
        ld      c, a
        inc     h
        ld      a, (hl)
        xor     e
        ld      b, a
        inc     h
        ld      a, (hl)
        xor     d
