bool qr_generate(const char * embed_str, uint16_t len) NONBANKED {

    if (len > QR_MAX_PAYLOAD_BYTES) {
        return false;
    }

    uint8_t save_bank = CURRENT_BANK;
    SWITCH_ROM(BANK(qrcodegen));

    qrcodegen(embed_str, len);

    SWITCH_ROM(save_bank);

    return true;
}


void qr_render(void) NONBANKED
{
    uint8_t save_bank = CURRENT_BANK;
    uint8_t ty;

    SWITCH_ROM(BANK(qrcodegen));

    HIDE_SPRITES;
    BGP_REG = 0xE4;

    VBK_REG = 0;
    set_bkg_data(0, 16, qr_tiles);

    VBK_REG = 1;
    fill_bkg_rect(0, 0, 20, 18, 0);
    VBK_REG = 0;
    fill_bkg_rect(0, 0, 20, 18, 0);

    for (ty = 0; ty < 16; ty++) {
        uint8_t row[16];
        uint8_t tx;
        uint8_t y0 = (uint8_t)(ty << 1);
        for (tx = 0; tx < 16; tx++) {
            uint8_t x0 = (uint8_t)(tx << 1);
            uint8_t bits = 0;
            if (x0 < 31 && y0 < 31 && !qr(x0, y0)) bits |= 1;
            if ((uint8_t)(x0 + 1) < 31 && y0 < 31 && !qr((uint8_t)(x0 + 1), y0)) bits |= 2;
            if (x0 < 31 && (uint8_t)(y0 + 1) < 31 && !qr(x0, (uint8_t)(y0 + 1))) bits |= 4;
            if ((uint8_t)(x0 + 1) < 31 && (uint8_t)(y0 + 1) < 31 && !qr((uint8_t)(x0 + 1), (uint8_t)(y0 + 1))) bits |= 8;
            row[tx] = bits;
        }
        set_bkg_tiles(2, (uint8_t)(1 + ty), 16, 1, row);
    }

    SWITCH_ROM(save_bank);
}
